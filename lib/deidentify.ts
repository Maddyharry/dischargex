const patterns: RegExp[] = [
  /\bHN\s*:\s*\w+\b/gi,
  /\bAN\s*:\s*\w+\b/gi,
  /\bCID\s*:\s*\d{10,13}\b/gi,
  /\bPID\s*:\s*\d{10,13}\b/gi,
  /\bMRN\s*:\s*[A-Z0-9-]+\b/gi,
  /\b\d{13}\b/g,
  /\b[0-9]{9,12}\b/g,
  /(นาย|นาง|น\.ส\.|ด\.ช\.|ด\.ญ\.)\s*[ก-๙]+\s*[ก-๙]+/g,
  /\b(Mr|Mrs|Miss|Ms)\.?\s+[A-Za-z]+\s+[A-Za-z]+\b/g,
  /\b0\d{1,2}-?\d{3}-?\d{4}\b/g,
  /\b\d{1,3}\/\d+\s*[A-Za-zก-๙.\s]+(Road|Rd\.|Street|St\.|Soi|หมู่|ต\.|อ\.|จ\.)/gi,
  // แพทย์เจ้าของไข้ / แพทย์ผู้ตรวจ
  /(นพ\.|น\.พ\.|พญ\.|นายแพทย์|แพทย์หญิง)\s*[ก-๙]+\s*[ก-๙]*/g,
  // พยาบาลผู้ดูแล (เฉพาะรูปแบบระบุชื่อต่อท้ายชัดเจน กันตัด "พยาบาล" ที่ใช้เป็นคำทั่วไปในบันทึกทางคลินิก)
  /พยาบาล\s*(?:ผู้ดูแล|เวร|ประจำ)?\s*[:：]\s*[ก-๙]+\s*[ก-๙]*/g,
  // ชื่อโรงพยาบาล
  /(โรงพยาบาล|รพ\.)\s*[ก-๙A-Za-z]+/g,
];

export function deidentify(text: string) {
  let t = text.replace(/\s+/g, " ").trim();
  for (const p of patterns) t = t.replace(p, "[REDACTED]");
  return t;
}